import turtle
from turtle import *
t = Turtle()
def rectangle():
    t.forward(100)
    t.left(90)
    t.forward(125)
    t.left(90)
    t.forward(100)
    t.left(90)
    t.forward(125)
    t.left(90)
rectangle()
t.right(180)
t.forward(150)
t.left(180)

def triangle():
    t.forward(90)
    t.left(120)
    t.forward(90)
    t.left(120)
    t.forward(90)
    t.left(120)
triangle()

